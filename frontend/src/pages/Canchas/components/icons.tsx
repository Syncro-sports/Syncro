export const renderChipIcon = (text: string) => {
  const t = text.toLowerCase();
  let iconName = "";

  if (t.includes("fútbol") || t.includes("futbol") || t.includes("cancha")) {
    iconName = "football-5.svg";
  } else if (
    t.includes("césped") ||
    t.includes("cesped") ||
    t.includes("natural") ||
    t.includes("sintético") ||
    t.includes("sintetico")
  ) {
    iconName = "artificial-grass.svg";
  } else if (t.includes("iluminación") || t.includes("iluminacion") || t.includes("led") || t.includes("luz")) {
    iconName = "led-lighting.svg";
  } else if (t.includes("vestuario") || t.includes("locker") || t.includes("cemento")) {
    iconName = "locker-rooms.svg";
  } else if (t.includes("estacionamiento") || t.includes("parking") || t.includes("cochera")) {
    iconName = "parking.svg";
  } else if (t.includes("parrilla") || t.includes("asador") || t.includes("quincho")) {
    iconName = "grill-area.svg";
  } else if (t.includes("buffet") || t.includes("bar") || t.includes("cantina") || t.includes("café")) {
    iconName = "buffet.svg";
  } else if (t.includes("wifi") || t.includes("internet")) {
    iconName = "wifi.svg";
  } else if (t.includes("ducha") || t.includes("calefaccionada")) {
    iconName = "showers.svg";
  } else if (t.includes("premium") || t.includes("vip") || t.includes("destacado")) {
    iconName = "premium-complex.svg";
  } else if (t.includes("familiar") || t.includes("grupo") || t.includes("ambiente")) {
    iconName = "family-friendly.svg";
  }

  if (iconName) {
    return (
      <img
        src={`${import.meta.env.BASE_URL}assets/icons/${iconName}`}
        alt=""
        style={{ width: "16px", height: "16px", display: "inline-block" }}
      />
    );
  }

  return <CheckIcon />;
};
